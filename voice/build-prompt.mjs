// Regenerates prompt.js from system-prompt.md (text between BEGIN/END PROMPT markers).
import { readFileSync, writeFileSync } from 'node:fs';
const md = readFileSync(new URL('./system-prompt.md', import.meta.url), 'utf8');
const m = md.match(/<!-- BEGIN PROMPT -->([\s\S]*?)<!-- END PROMPT -->/);
if (!m) throw new Error('markers not found');
writeFileSync(new URL('./prompt.js', import.meta.url), '// Generated by build-prompt.mjs from system-prompt.md. Do not edit by hand.\nexport const SYSTEM_PROMPT = ' + JSON.stringify(m[1].trim()) + ';\n');
console.log('prompt.js written,', m[1].trim().length, 'chars');
